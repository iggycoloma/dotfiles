#!/usr/bin/env bash
# prompt-stats.sh -- Regenerate docs/prompt-stats.md from the tracked prompt files.
#
# Token figures use the bytes/4 heuristic (English prose averages ~4 bytes per
# token for Claude and GPT tokenizers; real counts vary by ~10-20%). The
# loading graph is encoded here by hand because it IS the architecture --
# change AGENTS.md "Agent instruction architecture" first, then this script.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOTFILES_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
COMMITTED="$DOTFILES_DIR/docs/prompt-stats.md"
OUT="$COMMITTED"

# --check: regenerate to a temp file and fail if the committed doc differs,
# so CI catches a prompt edit whose stats were not regenerated.
CHECK=false
if [[ "${1:-}" == "--check" ]]; then
    CHECK=true
    OUT="$(mktemp)"
    trap 'rm -f "$OUT"' EXIT
fi

bytes() { wc -c < "$DOTFILES_DIR/$1"; }
lines() { wc -l < "$DOTFILES_DIR/$1" | tr -d '[:space:]'; }
tok() { echo $(( $1 / 4 )); }

B_CLAUDE_GLOBAL=$(bytes claude-code/CLAUDE.md)
B_CODEX_GLOBAL=$(bytes codex/AGENTS.md)
B_COPILOT_GLOBAL=$(bytes copilot/copilot-instructions.md)
B_STYLE=$(bytes agent-prompts/writing-style.md)
B_ENG=$(bytes agent-prompts/engineering-conventions.md)
B_WT=$(bytes agent-prompts/worktrees.md)
B_FORGE=$(bytes agent-prompts/forge.md)
B_AGENTS_ROOT=$(bytes AGENTS.md)
B_CLAUDE_ROOT=$(bytes CLAUDE.md)
B_RULE_DENY=$(bytes .claude/rules/deny-list-semantics.md)
B_WT_DOC=$(bytes docs/wt-maintenance.md)
B_COPILOT_REPO=$(bytes .github/copilot-instructions.md)

# Per-model fragments load only for Claude sessions on their model, so they
# count as conditional context rather than table rows; README.md documents the
# mechanism and never loads.
MODEL_ADJ=""
for f in "$DOTFILES_DIR"/claude-code/model-adjustments/*.md; do
    [[ -e "$f" ]] || continue
    base="$(basename "$f" .md)"
    [[ "$base" == "README" ]] && continue
    MODEL_ADJ+="${MODEL_ADJ:+, }\`$base\` at $(tok "$(wc -c < "$f")") tokens"
done

FRAGS=$(( B_STYLE + B_ENG + B_WT ))
CODEX_CAP=32768

row() { # path condition loads lines bytes incl_bytes in_codex_chain(yes/no)
    local budget="--"
    [[ "$7" == "yes" ]] && budget="$(( 100 * $6 / CODEX_CAP ))%"
    # shellcheck disable=SC2016  # backticks are literal markdown, not a subshell
    printf '| `%s` | %s | %s | %s | %s | %s | %s |\n' \
        "$1" "$2" "$3" "$4" "$(tok "$5")" "$(tok "$6")" "$budget"
}

{
cat <<'HEADER'
# Prompt file stats

Generated by `bin/prompt-stats.sh` (`make prompt-stats`) -- do not edit the numbers by hand.
Token figures are the bytes/4 heuristic; real tokenizer counts vary by ~10-20%.
The loading graph mirrors the "Agent instruction architecture" section of `AGENTS.md`.

Inclusive cost = the file plus everything it pulls in when it loads.
The Codex-budget column shows the inclusive size against the 32 KiB `project_doc_max_bytes` cap, and only for files in the Codex project-doc chain (root `AGENTS.md`).

| File | Loaded when | Loads / triggers | Lines | ~Tokens (excl) | ~Tokens (incl) | vs Codex 32 KiB |
|------|-------------|------------------|-------|----------------|----------------|-----------------|
HEADER

row claude-code/CLAUDE.md "every Claude session, all projects (deployed to ~/.claude)" "imports 3 \`agent-prompts/\` fragments at launch; triggers forge.md for forge tasks" "$(lines claude-code/CLAUDE.md)" "$B_CLAUDE_GLOBAL" $(( B_CLAUDE_GLOBAL + FRAGS )) no
row codex/AGENTS.md "every Codex session, all projects (deployed to ~/.codex)" "directs a session-start read of the fragments (worktrees.md and forge.md only for matching tasks)" "$(lines codex/AGENTS.md)" "$B_CODEX_GLOBAL" $(( B_CODEX_GLOBAL + FRAGS )) no
row copilot/copilot-instructions.md "every Copilot session, all projects (deployed to ~/.copilot)" "same session-start directive as Codex" "$(lines copilot/copilot-instructions.md)" "$B_COPILOT_GLOBAL" $(( B_COPILOT_GLOBAL + FRAGS )) no
row agent-prompts/writing-style.md "via each global file above" "nothing" "$(lines agent-prompts/writing-style.md)" "$B_STYLE" "$B_STYLE" no
row agent-prompts/engineering-conventions.md "via each global file above" "nothing" "$(lines agent-prompts/engineering-conventions.md)" "$B_ENG" "$B_ENG" no
row agent-prompts/worktrees.md "Claude: always (import); Codex/Copilot: worktree tasks" "nothing" "$(lines agent-prompts/worktrees.md)" "$B_WT" "$B_WT" no
row agent-prompts/forge.md "all tools: forge tasks only (trigger line or forge/review-pr/create-pr skill)" "nothing" "$(lines agent-prompts/forge.md)" "$B_FORGE" "$B_FORGE" no
row AGENTS.md "every session in this repo, all tools" "triggers \`docs/wt-maintenance.md\` before editing wt implementation files" "$(lines AGENTS.md)" "$B_AGENTS_ROOT" "$B_AGENTS_ROOT" yes
row CLAUDE.md "every Claude session in this repo" "imports \`@AGENTS.md\` at launch" "$(lines CLAUDE.md)" "$B_CLAUDE_ROOT" $(( B_CLAUDE_ROOT + B_AGENTS_ROOT )) no
row .claude/rules/deny-list-semantics.md "Claude touches \`claude-code/settings*.json\` or \`claude-code/commands/**\`" "nothing" "$(lines .claude/rules/deny-list-semantics.md)" "$B_RULE_DENY" "$B_RULE_DENY" no
row docs/wt-maintenance.md "explicit trigger in AGENTS.md before wt edits" "nothing" "$(lines docs/wt-maintenance.md)" "$B_WT_DOC" "$B_WT_DOC" no
row .github/copilot-instructions.md "every Copilot session in this repo" "nothing" "$(lines .github/copilot-instructions.md)" "$B_COPILOT_REPO" "$B_COPILOT_REPO" no

CLAUDE_TOTAL=$(( B_CLAUDE_GLOBAL + FRAGS + B_CLAUDE_ROOT + B_AGENTS_ROOT ))
CODEX_TOTAL=$(( B_CODEX_GLOBAL + FRAGS + B_AGENTS_ROOT ))
COPILOT_TOTAL=$(( B_COPILOT_GLOBAL + FRAGS + B_COPILOT_REPO ))

cat <<TOTALS

## Always-loaded totals per harness (a session in this repo)

| Harness | Composition | ~Tokens |
|---------|-------------|---------|
| Claude Code | global CLAUDE.md + 3 fragments + root CLAUDE.md + @AGENTS.md import | $(tok $CLAUDE_TOTAL) |
| Codex | global AGENTS.md + session-start fragments + root AGENTS.md | $(tok $CODEX_TOTAL) |
| Copilot | global instructions + session-start fragments + repo instructions | $(tok $COPILOT_TOTAL) |

Conditional context on top of these: the deny-list rule ($(tok "$B_RULE_DENY") tokens, path-scoped), the wt runbook ($(tok "$B_WT_DOC") tokens, explicit trigger), the forge fragment ($(tok "$B_FORGE") tokens, forge tasks only, all tools), each \`claude-code/model-adjustments/\` fragment for every Claude session on its model ($MODEL_ADJ), and for Codex/Copilot the worktrees fragment counts only when a task involves worktrees.

## Reading the numbers

- **Lines matter independently of tokens for Claude**: adherence degrades on files past ~200 lines (per the Claude Code memory docs), so a file can be token-cheap and still worth splitting.
- **The Codex budget column is a ceiling, not a target**: Codex truncates the project-doc chain at 32 KiB, so root AGENTS.md growth eventually silences whatever loads after it.
- **Inclusive vs exclusive gaps show coupling**: a small file with a large inclusive cost (root CLAUDE.md) is cheap to read but expensive to load, and trimming it does nothing -- the import is where the tokens are.
TOTALS
} > "$OUT"

if $CHECK; then
    if cmp -s "$OUT" "$COMMITTED"; then
        echo "prompt-stats: docs/prompt-stats.md is current"
    else
        echo "prompt-stats: docs/prompt-stats.md is stale -- run 'make prompt-stats' and commit the result" >&2
        diff -u "$COMMITTED" "$OUT" >&2 || true
        exit 1
    fi
else
    echo "wrote $OUT"
fi
