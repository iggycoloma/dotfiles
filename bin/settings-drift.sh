#!/usr/bin/env bash
# settings-drift.sh -- Catch the two ways this repo's settings files drift apart.
#
# Class 1 -- host vs container variants. The three-tier sandbox posture
# (docs/sandbox.md) ships two settings files per agentic CLI:
#   - claude-code/settings.json          (host: sandbox.enabled=true)
#   - claude-code/settings.container.json (container: sandbox.enabled=false)
#   - codex/config.toml                  (host: sandbox_mode=workspace-write)
#   - codex/config.container.toml        (container: sandbox_mode=danger-full-access)
#
# The sandbox block is intentionally different per tier; everything else
# (permissions, hooks, statusLine, approval_policy, etc.) MUST stay in sync.
# The Claude pair is generated by bin/sync-settings.sh, so this is its verifier;
# the Codex pair is hand-maintained and this is its only guard.
#
# Class 2 -- Read/Write/Edit parity inside settings.json. Every credential path
# in permissions.deny[] is repeated three times, once per file tool. They are
# maintained by hand and must stay identical in content and order, or a path
# ends up blocked for Read but writable through Edit. Deliberate asymmetries
# are declared in PARITY_WRITE_EDIT_ONLY below; anything else is a bug.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOTFILES_DIR="${DOTFILES_DIR:-$(cd "$SCRIPT_DIR/.." && pwd)}"

# shellcheck source=../bootstrap/logging.sh
source "$DOTFILES_DIR/bootstrap/logging.sh"

QUIET=false
JSON_OUTPUT=false
ERRORS=0

# Paths deliberately denied for Write and Edit but NOT for Read. Each entry
# needs a reason -- an undocumented asymmetry is indistinguishable from a
# forgotten line.
#
#   ~/.claude/projects/*/memory/**
#       The auto-memory surface. Writing is denied because it is untracked by
#       git and injected into context unreviewed (claude-code/CLAUDE.md
#       "Memory"). Reading stays allowed so the contents remain auditable --
#       you cannot review a surface you are blocked from opening.
#
# The tilde is matched literally against the text in settings.json -- Claude
# Code expands it, this script never touches the filesystem here.
# shellcheck disable=SC2088
PARITY_WRITE_EDIT_ONLY=(
    '~/.claude/projects/*/memory/**'
)

usage() {
    cat <<'HELP'
Usage: settings-drift.sh [options]

Compare host vs container settings variants for Claude Code and Codex.
Reports drift on every key outside the per-tier sandbox block.

Options:
  --quiet   Suppress per-file success lines; only report drift
  --json    Emit findings as JSONL (one object per drift)
  -h, --help  Show this help

Exit code:
  0  variants in sync
  1  drift detected (incl. one half of a variant pair missing)
HELP
}

parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --quiet) QUIET=true; shift ;;
            --json)  JSON_OUTPUT=true; shift ;;
            -h|--help) usage; exit 0 ;;
            *) log_error "Unknown option: $1"; usage; return 1 ;;
        esac
    done
}

emit_drift() {
    local pair="$1" exclude_key="$2" diff_output="$3"
    ERRORS=$((ERRORS + 1))
    if [[ "$JSON_OUTPUT" == true ]]; then
        jq -cn \
            --arg pair "$pair" \
            --arg exclude "$exclude_key" \
            --arg diff "$diff_output" \
            '{pair: $pair, excludeKey: $exclude, status: "drift", diff: $diff}'
    else
        log_error "$pair: drift detected (excluding $exclude_key)"
        printf '%s\n' "$diff_output" | sed 's/^/    /'
    fi
}

emit_ok() {
    local pair="$1" exclude_key="$2"
    if [[ "$JSON_OUTPUT" == true ]]; then
        jq -cn \
            --arg pair "$pair" \
            --arg exclude "$exclude_key" \
            '{pair: $pair, excludeKey: $exclude, status: "ok"}'
    elif [[ "$QUIET" != true ]]; then
        log_success "$pair: in sync (excluding $exclude_key)"
    fi
}

emit_skip() {
    local pair="$1" reason="$2"
    if [[ "$JSON_OUTPUT" == true ]]; then
        jq -cn \
            --arg pair "$pair" \
            --arg reason "$reason" \
            '{pair: $pair, status: "skipped", reason: $reason}'
    else
        log_warn "$pair: $reason"
    fi
}

# Missing one half of a variant pair is itself a drift class (deletion bug).
# Report as drift, not skip, so make lint catches it.
emit_missing() {
    local pair="$1" reason="$2"
    ERRORS=$((ERRORS + 1))
    if [[ "$JSON_OUTPUT" == true ]]; then
        jq -cn \
            --arg pair "$pair" \
            --arg reason "$reason" \
            '{pair: $pair, status: "drift", reason: $reason}'
    else
        log_error "$pair: $reason"
    fi
}

check_json_drift() {
    local pair="$1" host="$2" container="$3" exclude="$4"

    # A missing half is the deletion form of drift -- exactly the bug class
    # this linter exists to catch. Report and fail, do not silently skip.
    if [[ ! -f "$host" ]]; then
        emit_missing "$pair" "host variant missing: $host"
        return 0
    fi
    if [[ ! -f "$container" ]]; then
        emit_missing "$pair" "container variant missing: $container"
        return 0
    fi

    local h c diff_out
    if ! h=$(jq -S "del($exclude)" "$host" 2>&1); then
        emit_skip "$pair" "host variant not valid JSON: $h"
        return 0
    fi
    if ! c=$(jq -S "del($exclude)" "$container" 2>&1); then
        emit_skip "$pair" "container variant not valid JSON: $c"
        return 0
    fi

    if [[ "$h" == "$c" ]]; then
        emit_ok "$pair" "$exclude"
        return 0
    fi

    diff_out=$(diff <(printf '%s\n' "$h") <(printf '%s\n' "$c") || true)
    emit_drift "$pair" "$exclude" "$diff_out"
}

# Canonical yq output for a given input makes a string compare safe here.
check_toml_drift() {
    local pair="$1" host="$2" container="$3" exclude="$4"

    if [[ ! -f "$host" ]]; then
        emit_missing "$pair" "host variant missing: $host"
        return 0
    fi
    if [[ ! -f "$container" ]]; then
        emit_missing "$pair" "container variant missing: $container"
        return 0
    fi
    if ! command -v yq >/dev/null 2>&1; then
        emit_skip "$pair" "yq not installed; cannot diff TOML"
        return 0
    fi

    # JSON as the intermediate makes the compare whitespace- and key-order-insensitive.
    local h c diff_out
    if ! h=$(yq -p toml -o json "del($exclude)" "$host" 2>&1 | jq -S '.'); then
        emit_skip "$pair" "host variant not valid TOML: $h"
        return 0
    fi
    if ! c=$(yq -p toml -o json "del($exclude)" "$container" 2>&1 | jq -S '.'); then
        emit_skip "$pair" "container variant not valid TOML: $c"
        return 0
    fi

    if [[ "$h" == "$c" ]]; then
        emit_ok "$pair" "$exclude"
        return 0
    fi

    diff_out=$(diff <(printf '%s\n' "$h") <(printf '%s\n' "$c") || true)
    emit_drift "$pair" "$exclude" "$diff_out"
}

check_deny_parity() {
    local pair="$1" file="$2"

    if [[ ! -f "$file" ]]; then
        emit_missing "$pair" "settings file missing: $file"
        return 0
    fi

    local exempt_json findings

    # Fail closed on a structurally unusable file. A missing or empty
    # permissions.deny[] is not "nothing to check" -- it is the Tier-1 deny list
    # having been deleted, which is precisely the regression this guard exists
    # to catch. Treat it as drift, never as a skip.
    if ! jq -e '(.permissions.deny // []) | type == "array" and length > 0' \
        "$file" >/dev/null 2>&1; then
        emit_parity_drift "$pair" \
            "permissions.deny[] is missing, empty, or unreadable in $file -- the credential deny list must never be absent"
        return 0
    fi

    exempt_json=$(printf '%s\n' "${PARITY_WRITE_EDIT_ONLY[@]}" | jq -R . | jq -sc .)

    # Order matters as well as membership -- a reordering is the first sign
    # someone appended to one block instead of inserting into all three. The
    # two classes need different reporting: jq's array `-` is set difference
    # and says nothing at all about a pure reordering, so that case reports the
    # first diverging index instead, or the message names no actionable path.
    if ! findings=$(jq -r --argjson exempt "$exempt_json" '
        def deny_for($tool):
            [ .permissions.deny[]
              | select(startswith($tool + "("))
              | ltrimstr($tool + "(")
              | .[:-1] ];
        def strip_exempt: map(select(. as $p | $exempt | index($p) | not));

        # Membership difference if there is one, otherwise the first index at
        # which two same-membership lists disagree.
        def explain($a; $b; $a_name; $b_name):
            (($a - $b) | length) as $only_a |
            (($b - $a) | length) as $only_b |
            if $only_a > 0 or $only_b > 0 then
                "only in \($a_name): \($a - $b); only in \($b_name): \($b - $a)"
            else
                ( [ range(0; $a | length) | select($a[.] != $b[.]) ] | first ) as $i |
                "same entries in a different order -- first divergence at index \($i): \($a_name) has \($a[$i]), \($b_name) has \($b[$i])"
            end;

        deny_for("Read")                as $read  |
        deny_for("Write")               as $write |
        deny_for("Edit")                as $edit  |
        ($write | strip_exempt)         as $write_core |
        [
          if $write != $edit then
            "Write/Edit deny lists differ -- \(explain($write; $edit; "Write"; "Edit"))"
          else empty end,
          if $read != $write_core then
            "Read differs from Write/Edit (after declared exemptions) -- \(explain($write_core; $read; "Write/Edit"; "Read"))"
          else empty end
        ] | .[]
    ' "$file" 2>&1); then
        # jq failed on a file that already passed the structural probe above,
        # so this is a real defect in the query or an unexpected shape. Fail
        # closed rather than waving it through.
        emit_parity_drift "$pair" "deny-parity query failed: $findings"
        return 0
    fi

    if [[ -z "$findings" ]]; then
        emit_parity_ok "$pair"
        return 0
    fi

    emit_parity_drift "$pair" "$findings"
}

emit_parity_ok() {
    local pair="$1"
    if [[ "$JSON_OUTPUT" == true ]]; then
        jq -cn --arg pair "$pair" \
            '{pair: $pair, check: "deny-parity", status: "ok"}'
    elif [[ "$QUIET" != true ]]; then
        log_success "$pair: Read/Write/Edit deny lists in parity"
    fi
}

emit_parity_drift() {
    local pair="$1" findings="$2"
    ERRORS=$((ERRORS + 1))
    if [[ "$JSON_OUTPUT" == true ]]; then
        jq -cn --arg pair "$pair" --arg findings "$findings" \
            '{pair: $pair, check: "deny-parity", status: "drift", findings: $findings}'
    else
        log_error "$pair: Read/Write/Edit deny lists out of parity"
        printf '%s\n' "$findings" | sed 's/^/    /'
    fi
}

main() {
    parse_args "$@"

    command -v jq >/dev/null 2>&1 || log_and_return error 2 "jq is required"

    if [[ "$JSON_OUTPUT" != true ]]; then
        log_section "settings-drift: comparing host vs container variants"
    fi

    check_json_drift \
        "claude-code" \
        "$DOTFILES_DIR/claude-code/settings.json" \
        "$DOTFILES_DIR/claude-code/settings.container.json" \
        ".sandbox"

    check_toml_drift \
        "codex" \
        "$DOTFILES_DIR/codex/config.toml" \
        "$DOTFILES_DIR/codex/config.container.toml" \
        ".sandbox_mode"

    # Only the host variant is checked: the container variant is generated from
    # it by bin/sync-settings.sh, so it inherits the deny list verbatim.
    check_deny_parity \
        "claude-code" \
        "$DOTFILES_DIR/claude-code/settings.json"

    if [[ "$JSON_OUTPUT" != true ]]; then
        if (( ERRORS > 0 )); then
            log_error "settings-drift: $ERRORS variant pair(s) drifted"
        else
            log_success "settings-drift: all variants in sync"
        fi
    fi

    (( ERRORS == 0 ))
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    main "$@"
fi
